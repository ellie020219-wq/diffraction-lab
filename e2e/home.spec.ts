import { expect, test } from '@playwright/test'

test('首頁免運算預覽開口，支援鍵盤、卡片切換及響應式光路圖', async ({ page, isMobile }) => {
  await page.goto('./')
  const nav = page.getByRole('navigation', { name: '網站導覽' })
  await expect(nav.getByRole('link', { name: '首頁' })).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('光的干涉與繞射互動實驗室')
  const bench = page.getByRole('region', { name: '光學實驗架構' })
  const svg = bench.getByRole('img')
  await expect(bench.getByText('示意圖，非實際比例')).toBeVisible()
  await expect(bench.getByText('λ = 632.8 nm')).toBeVisible()
  await expect(bench.getByText('L = 2 m · 從孔徑至屏幕')).toBeVisible()
  await expect(svg.locator('[data-slit-opening]')).toHaveCount(1)

  const options = page.getByRole('group', { name: '孔徑預覽' })
  const double = options.getByRole('button', { name: '雙狹縫' })
  if (isMobile) await double.tap()
  else {
    await page.keyboard.press('Tab')
    await expect(page.getByRole('link', { name: '跳至主要內容' })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('main')).toBeFocused()
    await double.focus()
    await double.press('Space')
  }
  await expect(svg.locator('[data-slit-opening]')).toHaveCount(2)
  await options.getByRole('button', { name: 'N 縫光柵' }).click()
  await expect(svg.locator('[data-slit-opening]')).toHaveCount(5)

  const experimentCards = page.getByRole('group', { name: '實驗類型' })
  await experimentCards.getByRole('button', { name: /二維孔徑與遠場繞射/ }).click()
  const opening = svg.locator('[data-aperture-outline]')
  await expect(opening).toHaveAttribute('data-shape', 'circle')
  const circle = (await opening.getAttribute('d'))!
  await expect(options.getByRole('button')).toHaveCount(9)
  await options.getByRole('button', { name: '三角形' }).click()
  await expect(svg).toHaveAccessibleName(/三角形/)
  await expect(opening).toHaveAttribute('data-shape', 'triangle')
  await expect(opening).not.toHaveAttribute('d', circle)
  const far = (await svg.locator('[data-screen-position]').getAttribute('data-screen-position'))!
  await experimentCards.getByRole('button', { name: /近場與遠場比較/ }).click()
  await expect(svg.locator('[data-screen-position]')).not.toHaveAttribute('data-screen-position', far)
  await expect(bench.getByText(/z 可手動調整/)).toBeVisible()
  expect(page.workers()).toHaveLength(0)
  expect(await page.locator('canvas').count()).toBe(0)

  // Check each label stays inside its card at the smallest supported width.
  if (isMobile) await page.setViewportSize({ width: 320, height: 720 })
  const overflows = await bench.locator('.home-stages > div').evaluateAll((cards) =>
    cards.map((card) => card.scrollWidth - card.clientWidth))
  expect(overflows.every((overflow) => overflow <= 1)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
})

test('由三張實驗卡啟動對應模擬，返回首頁後仍保留各實驗參數', async ({ page }) => {
  await page.goto('./')
  const start = page.getByRole('link', { name: '開始實驗' })
  const back = page.getByRole('link', { name: '返回首頁' })
  const nav = page.getByRole('navigation', { name: '網站導覽' })
  const cards = page.getByRole('group', { name: '實驗類型' })
  const options = page.getByRole('group', { name: '孔徑預覽' })

  await options.getByRole('button', { name: '雙狹縫' }).click()
  await start.click()
  await expect(page).toHaveURL(/#\/slits$/)
  await expect(page.getByRole('button', { name: '雙狹縫' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('spinbutton', { name: /波長/ }).fill('529.5')
  await back.click()
  await expect(options.getByRole('button', { name: '雙狹縫' })).toHaveAttribute('aria-pressed', 'true')

  await cards.getByRole('button', { name: /二維孔徑與遠場繞射/ }).click()
  await options.getByRole('button', { name: '三角形' }).click()
  await start.click()
  await expect(page).toHaveURL(/#\/farfield$/)
  await expect(page.getByRole('img', { name: '三角形的二值透光孔徑' })).toBeVisible()
  await page.getByRole('region', { name: '二維繞射模擬' }).getByText('光學實驗架構示意圖', { exact: true }).click()
  await expect(page.getByRole('img', { name: /平行單色光垂直入射三角形/ })).toBeVisible()
  await page.getByRole('spinbutton', { name: '孔徑尺寸' }).fill('720')
  await page.getByRole('spinbutton', { name: '屏幕距離' }).fill('8200')
  await back.click()

  await cards.getByRole('button', { name: /近場與遠場比較/ }).click()
  await options.getByRole('button', { name: '三角形' }).click()
  await start.click()
  await expect(page).toHaveURL(/#\/comparison$/)
  const comparison = page.getByRole('region', { name: '近遠場比較', exact: true })
  await expect(comparison.getByRole('combobox', { name: '共同孔徑' })).toHaveValue('triangle')
  await expect(comparison.getByRole('spinbutton', { name: '孔徑尺寸' })).toHaveValue('720.00')
  await comparison.getByRole('spinbutton', { name: '傳播距離', exact: true }).fill('940')
  const field = comparison.getByRole('img', { name: 'Fresnel 近場強度圖' })
  await expect.poll(async () => Number(await field.getAttribute('data-distance'))).toBeCloseTo(0.94, 12)
  await back.click()
  await nav.getByRole('link', { name: '二維孔徑繞射' }).click()
  await expect(page.getByRole('spinbutton', { name: '屏幕距離' })).toHaveValue('8200')
  await nav.getByRole('link', { name: '一維干涉與繞射' }).click()
  await expect(page.getByRole('spinbutton', { name: /波長/ })).toHaveValue('529.5')
  await nav.getByRole('link', { name: '近場與遠場比較' }).click()
  await expect(comparison.getByRole('spinbutton', { name: '傳播距離', exact: true })).toHaveValue('940')
})

test('GitHub Pages 的深層連結可重新整理，並保留理論數值與模型入口', async ({ page }) => {
  await page.goto('./#/comparison')
  const comparison = page.getByRole('region', { name: '近遠場比較', exact: true })
  await expect(comparison.getByRole('img', { name: 'Fresnel 近場強度圖' })).toBeVisible()
  await page.reload()
  await expect(comparison.getByRole('img', { name: 'Fraunhofer 遠場近似強度圖' })).toBeVisible()
  await page.getByRole('link', { name: '模型說明', exact: true }).click()
  await expect(page.getByRole('heading', { name: '模型說明' })).toBeVisible()
  await expect(page.getByRole('link', { name: '前往近遠場比較' })).toHaveAttribute('href', '#/comparison')

  await page.goto('./#results')
  await expect(page.getByRole('heading', { name: '理論與數值' })).toBeInViewport()
  await page.reload()
  await expect(page.getByRole('heading', { name: '理論與數值' })).toBeInViewport()
  await page.getByRole('link', { name: '模擬實驗', exact: true }).click()
  await expect(page.getByRole('group', { name: '狹縫模式' })).toBeInViewport()
  await page.goto('./#model')
  await expect(page.getByRole('heading', { name: '模型說明' })).toBeVisible()
  await page.getByRole('link', { name: '返回首頁' }).click()
  await expect(page.getByRole('heading', { name: '選擇實驗' })).toBeVisible()
})
